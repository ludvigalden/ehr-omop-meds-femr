"""KDL emit and verify for the CLMBR concept set, and its committed manifest.

``<vocabulary_id>.kdl`` (one per vocabulary, git-ignored) lists every concept
of that vocabulary with the dictionary entry types it appears under and, when
the import was enriched from Athena, its OMOP ``concept_id``, ``domain_id`` and
``standard_concept``. Nothing else: no names, weights, value bins or age
statistics. ``manifest.json`` (committed) holds counts and hashes only.

``verify_kdl`` re-derives the per-vocabulary counts, the total and the
concept-list hash from the KDL files and compares them with the manifest.
"""

from __future__ import annotations

import importlib
import json
from collections.abc import Iterable
from pathlib import Path
from typing import Protocol, cast

from pydantic import ValidationError

from omopmap.artifacts.contract import CARE_SITE_VOCABULARY, CONTRACT_VERSION, check_compatible
from omopmap.artifacts.errors import ManifestError, MissingFileError, UnexpectedFileError
from omopmap.artifacts.manifest import concept_list_sha256
from omopmap.artifacts.models import ClmbrManifest
from omopmap.clmbr.importer import ClmbrConcept, ClmbrConceptSet
from omopmap.clmbr.model import ENTRY_TYPES
from omopmap.clmbr.source import ResolvedDictionary

MANIFEST_JSON = "manifest.json"
KDL_SUFFIX = ".kdl"
_HEADER = (
    "// Generated by `omopmap clmbr import` from the CLMBR dictionary named in the\n"
    "// context node. Local only: concept lists are never committed.\n"
)


class _Node(Protocol):
    @property
    def name(self) -> str: ...
    @property
    def args(self) -> list[object]: ...
    @property
    def properties(self) -> dict[str, object]: ...
    @property
    def children(self) -> list[_Node]: ...


class _Document(Protocol):
    @property
    def nodes(self) -> list[_Node]: ...
    def dump(self, options: object = ..., /) -> str: ...


class _Versions(Protocol):
    kdl_2: int


class _Ckdl(Protocol):
    """The part of ``ckdl`` (a C extension without type information) used here."""

    KdlVersion: _Versions
    ParseError: type[Exception]

    def Node(self, annotation: None, name: str, /, *args: object, **props: object) -> _Node: ...  # noqa: N802
    def Document(self, *nodes: _Node) -> _Document: ...  # noqa: N802
    def EmitterOptions(self, *, version: int) -> object: ...  # noqa: N802
    def parse(self, text: str, /, version: int) -> _Document: ...


_ckdl = cast(_Ckdl, importlib.import_module("ckdl"))


def _node(name: str, *args: object, **properties: object) -> _Node:
    # ckdl reads a leading pair of strings as (type annotation, name); passing
    # None first selects the plain-name signature.
    return _ckdl.Node(None, name, *args, **properties)


class KdlError(ManifestError):
    """A KDL concept file is malformed or disagrees with the manifest."""


def kdl_filename(vocabulary_id: str) -> str:
    """``<vocabulary_id>.kdl``; fail closed on ids that are not safe file names."""
    if (
        not vocabulary_id
        or vocabulary_id.startswith(".")
        or any(ch in vocabulary_id for ch in "/\\\0\n")
    ):
        raise KdlError(f"vocabulary id {vocabulary_id!r} is not a safe file name")
    return f"{vocabulary_id}{KDL_SUFFIX}"


def build_manifest(concept_set: ClmbrConceptSet, source: ResolvedDictionary) -> ClmbrManifest:
    """The committed ``manifest.json`` for an import."""
    by_vocabulary = concept_set.by_vocabulary()
    return ClmbrManifest(
        contract_version=CONTRACT_VERSION,
        source_repo=source.repo,
        revision=source.revision,
        filename=source.filename,
        file_sha256=source.sha256,
        entry_type_counts=dict(concept_set.entry_type_counts),
        vocabulary_counts=by_vocabulary,
        total=sum(by_vocabulary.values()),
        care_site_excluded=concept_set.care_site_excluded,
        concept_list_sha256=concept_set.concept_list_sha256(),
    )


def _concept_node(concept: ClmbrConcept) -> _Node:
    children = [_node("clmbr-entry-types", *concept.entry_types)]
    if concept.omop is not None:
        properties: dict[str, str] = {"domain": concept.omop.domain_id}
        if concept.omop.standard_concept is not None:
            properties["standard"] = concept.omop.standard_concept
        children.append(_node("omop-concept-id", concept.omop.concept_id, **properties))
    return _node("concept", concept.ref.concept_code, *children)


def render_kdl(
    vocabulary_id: str,
    concepts: Iterable[ClmbrConcept],
    source: ResolvedDictionary,
    athena_sha256: str | None,
) -> str:
    """One vocabulary's KDL document (KDL 2)."""
    context = [
        _node("system", vocabulary_id),
        _node("source", source.repo),
        _node("revision", source.revision),
        _node("dictionary-sha256", source.sha256),
    ]
    if athena_sha256 is not None:
        context.append(_node("athena-concept-sha256", athena_sha256))
    nodes = [_node("context", *context), *(_concept_node(c) for c in concepts)]
    options = _ckdl.EmitterOptions(version=_ckdl.KdlVersion.kdl_2)
    return _HEADER + _ckdl.Document(*nodes).dump(options)


def render_files(
    concept_set: ClmbrConceptSet, source: ResolvedDictionary, athena_sha256: str | None
) -> dict[str, str]:
    """``{file name: KDL text}`` for every vocabulary of the concept set."""
    groups: dict[str, list[ClmbrConcept]] = {}
    for concept in concept_set.concepts:
        groups.setdefault(concept.ref.vocabulary_id, []).append(concept)
    return {
        kdl_filename(vocabulary): render_kdl(vocabulary, concepts, source, athena_sha256)
        for vocabulary, concepts in sorted(groups.items())
    }


def read_clmbr_manifest(path: Path) -> ClmbrManifest:
    """Parse and contract-check a CLMBR ``manifest.json``."""
    if not path.is_file():
        raise MissingFileError(f"{path} does not exist")
    text = path.read_text(encoding="utf-8")
    try:
        version = json.loads(text).get("contract_version")
    except (json.JSONDecodeError, AttributeError) as exc:
        raise ManifestError(f"{path.name} is not a JSON object: {exc}") from exc
    if not isinstance(version, str):
        raise ManifestError(f"{path.name} has no contract_version string")
    check_compatible(version)
    try:
        return ClmbrManifest.model_validate_json(text)
    except ValidationError as exc:
        raise ManifestError(f"{path.name} is invalid: {exc}") from exc


def _string_args(node: _Node, what: str) -> list[str]:
    args = node.args
    if not args or not all(isinstance(a, str) for a in args):
        raise KdlError(f"{what}: expected string arguments")
    return cast("list[str]", args)


def _context(document: _Document, name: str) -> dict[str, str]:
    nodes = document.nodes
    if not nodes or nodes[0].name != "context":
        raise KdlError(f"{name}: the first node must be `context`")
    values: dict[str, str] = {}
    for child in nodes[0].children:
        (value,) = _string_args(child, f"{name}: context {child.name}")
        values[child.name] = value
    return values


def parse_kdl(text: str) -> _Document:
    """Parse a KDL 2 document; fail closed with ``KdlError``."""
    try:
        return _ckdl.parse(text, version=2)
    except _ckdl.ParseError as exc:
        raise KdlError(f"not a KDL 2 document: {exc}") from exc


def read_kdl_codes(path: Path) -> tuple[str, dict[str, str], list[str]]:
    """``(system, context, codes)`` of one KDL file, codes in file order."""
    try:
        document = parse_kdl(path.read_text(encoding="utf-8"))
    except (KdlError, UnicodeDecodeError) as exc:
        raise KdlError(f"{path.name}: {exc}") from exc
    context = _context(document, path.name)
    system = context.get("system")
    if system is None:
        raise KdlError(f"{path.name}: context has no system")
    codes: list[str] = []
    for node in document.nodes[1:]:
        if node.name != "concept":
            raise KdlError(f"{path.name}: unexpected node {node.name!r}")
        (concept_code,) = _string_args(node, f"{path.name}: concept")
        children = {c.name: c for c in node.children}
        entry = children.get("clmbr-entry-types")
        if entry is None:
            raise KdlError(f"{path.name}: concept {concept_code!r} has no clmbr-entry-types")
        types = _string_args(entry, f"{path.name}: concept {concept_code!r} entry types")
        if types != [t for t in ENTRY_TYPES if t in types] or "unused" in types:
            raise KdlError(f"{path.name}: concept {concept_code!r} has invalid entry types")
        codes.append(f"{system}/{concept_code}")
    return system, context, codes


def verify_kdl(manifest_path: Path) -> ClmbrManifest:
    """Re-derive counts and the concept-list hash from the KDL files beside the manifest.

    The directory must hold exactly one KDL file per manifest vocabulary (no
    missing and no extra files), each naming the manifest's dictionary hash, with
    unique codes sorted by code point.
    """
    manifest = read_clmbr_manifest(manifest_path)
    root = manifest_path.parent
    expected = {kdl_filename(v) for v in manifest.vocabulary_counts}
    present = {p.name for p in root.iterdir() if p.is_file() and p.name.endswith(KDL_SUFFIX)}
    if not present:
        raise MissingFileError(
            f"no KDL files beside {manifest_path}; run `omopmap clmbr import` first"
        )
    missing, extra = sorted(expected - present), sorted(present - expected)
    if missing:
        raise MissingFileError(f"KDL files listed by the manifest are missing: {missing}")
    if extra:
        raise UnexpectedFileError(f"KDL files not in the manifest: {extra}")
    all_codes: list[str] = []
    counts: dict[str, int] = {}
    for name in sorted(present):
        system, context, codes = read_kdl_codes(root / name)
        if kdl_filename(system) != name or system == CARE_SITE_VOCABULARY:
            raise KdlError(f"{name}: context system {system!r} does not match the file name")
        if context.get("dictionary-sha256") != manifest.file_sha256:
            raise KdlError(f"{name}: dictionary-sha256 differs from the manifest's file_sha256")
        if codes != sorted(set(codes)):
            raise KdlError(f"{name}: concept codes must be unique and sorted")
        counts[system] = len(codes)
        all_codes.extend(codes)
    if counts != manifest.vocabulary_counts:
        raise ManifestError(
            f"KDL vocabulary counts {counts} differ from the manifest's "
            f"{manifest.vocabulary_counts}"
        )
    if len(all_codes) != manifest.total:
        raise ManifestError(
            f"KDL total {len(all_codes)} differs from the manifest's {manifest.total}"
        )
    digest = concept_list_sha256(all_codes)
    if digest != manifest.concept_list_sha256:
        raise ManifestError(
            f"KDL concept-list hash {digest} differs from the manifest's "
            f"{manifest.concept_list_sha256}"
        )
    return manifest


def write_kdl_dir(out: Path, files: dict[str, str], manifest: ClmbrManifest) -> None:
    """Write the KDL files and ``manifest.json`` into ``out``.

    ``out`` may be absent, empty, or hold only a previous ``manifest.json`` (the
    committed one), which is replaced. Existing KDL or other files fail closed, so
    a previous import is never mixed with a new one.
    """
    if out.exists():
        if not out.is_dir():
            raise UnexpectedFileError(f"{out} exists and is not a directory")
        leftovers = sorted(p.name for p in out.iterdir() if p.name != MANIFEST_JSON)
        if leftovers:
            raise UnexpectedFileError(
                f"{out} already holds {leftovers[:5]}; remove the previous import first"
            )
    out.mkdir(parents=True, exist_ok=True)
    for name, text in sorted(files.items()):
        (out / name).write_text(text, encoding="utf-8")
    (out / MANIFEST_JSON).write_text(manifest.to_json(), encoding="utf-8")
